"""Reproducible integration checks against the same physics used by the UI."""
import csv
import json
from pathlib import Path
import numpy as np
from simulator import DroneSim, DT

OUT = Path(__file__).resolve().parent / 'results'
OUT.mkdir(exist_ok=True)
results = []
for scenario, duration in [('hover', 20), ('waypoints', 90), ('disturbance', 22), ('linkloss', 25)]:
    sim = DroneSim()
    sim.reset(scenario)
    sim.start()
    for _ in range(round(duration / DT)):
        sim.step()
        if sim.complete or sim.phase == 'ABORTED': break
    sim.sample()
    s = sim.state()
    rows = sim.rows
    tail = [r for r in rows if r['time_s'] > (15 if scenario != 'linkloss' else 9)]
    tail_rmse = float(np.sqrt(np.mean([r['error_m']**2 for r in tail]))) if tail else None
    if scenario == 'waypoints': passed = s['complete'] and len(s['visited']) == 5 and s['phase'] == 'LANDED'
    elif scenario == 'linkloss': passed = s['complete'] and s['phase'] == 'LANDED' and not s['link']
    else: passed = s['phase'] == 'HOVER' and tail_rmse < .08 and abs(s['position'][2]-1.2) < .03
    gust_peak = max((r['error_m'] for r in rows if 7 <= r['time_s'] <= 12), default=0) if scenario == 'disturbance' else None
    if scenario == 'disturbance': passed = passed and gust_peak > .10
    result = {'scenario': scenario, 'passed': bool(passed), 'simulated_seconds': round(s['time'],2),
              'final_phase':s['phase'], 'final_position_m':s['position'], 'tail_rmse_m':tail_rmse,
              'visited':len(s['visited']), 'gust_peak_error_m':gust_peak, 'events':sim.events}
    results.append(result)
    with (OUT / f'{scenario}.csv').open('w',newline='') as f:
        w=csv.DictWriter(f,fieldnames=rows[0].keys());w.writeheader();w.writerows(rows)
    print(f"{scenario}: {'PASS' if passed else 'FAIL'} | {s['phase']} | t={s['time']:.1f}s | tail RMSE={tail_rmse}")
    sim.close()
(OUT / 'validation.json').write_text(json.dumps(results,indent=2))
lines = ['# Computed simulation results', '',
         'Generated by validate.py using the same Bullet model and controller as the live application.',
         'These are simulation results with assumed parameters and virtual position/height feedback, not hardware measurements.', '',
         '| Experiment | Result | Simulated duration | Outcome |',
         '|---|---|---|---|']
for r in results:
    outcome = (f"5/5 beacons, home return, floor contact and disarm" if r['scenario']=='waypoints' else
               'Command loss, 500 ms timeout, floor contact and disarm' if r['scenario']=='linkloss' else
               f"Final-window 3D position RMSE: {r['tail_rmse_m']:.4f} m")
    lines.append(f"| {r['scenario']} | {'PASS' if r['passed'] else 'FAIL'} | {r['simulated_seconds']} s | {outcome} |")
lines += ['', '## Acceptance criteria', '',
          '- Hover and disturbance: final phase HOVER, final height within 0.03 m of 1.2 m, and 3D error RMSE after 15 s below 0.08 m.',
          '- Disturbance also requires a measured position error excursion above 0.10 m during 7-12 s, proving that the gust actually affected the body.',
          '- Waypoints: all five beacons held within 0.15 m for 1 s each, return home and physical floor contact before disarm.',
          '- Link loss: disconnected state, timeout state transition and physical floor contact before disarm.', '',
          'Mission-wide position errors include target jumps and descent tracking; do not present those as hover accuracy.',
          'Seed: 1540. Integration step: 1/240 s. Nominal mass: 85 g. Nominal maximum thrust: 0.45 N per motor.', '',
          'See README.md for full assumptions, control equations and syllabus mapping.']
(OUT / 'VALIDATION_REPORT.md').write_text('\n'.join(lines),encoding='utf-8')
raise SystemExit(0 if all(r['passed'] for r in results) else 1)
